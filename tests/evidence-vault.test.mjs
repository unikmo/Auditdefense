import assert from 'node:assert/strict';
import vault from '../public/evidence-vault.js';
const ok={name:'a.pdf',type:'application/pdf',size:1000,attestedRedacted:true};
assert.equal(vault.validate(ok,{phiAllowed:false}).ok,true);
assert.equal(vault.validate({...ok,attestedRedacted:false},{phiAllowed:false}).ok,false,'Unattested file blocked while gates open.');
assert.equal(vault.validate({...ok,attestedRedacted:false},{phiAllowed:true}).ok,true);
assert.equal(vault.validate({...ok,type:'image/png'},{}).ok,false);
assert.equal(vault.validate({...ok,size:10*1024*1024},{}).ok,false);
assert.equal(vault.validate({...ok,size:0},{}).ok,false);
assert.equal(vault.validate({...ok,name:'../x.pdf'},{}).ok,false);
assert.equal(await vault.sha256Hex(new TextEncoder().encode('abc')),'ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad');
assert.equal(vault.objectPath({caseId:'c-1',fileId:'f_1'}),'evidence/c-1/f_1');
assert.throws(()=>vault.objectPath({caseId:'c/../x',fileId:'f'}));
assert.throws(()=>vault.metadata({sha256:'zz',originalType:'application/pdf',uploadedBy:'u1'}));
assert.throws(()=>vault.metadata({sha256:'a'.repeat(64),originalType:'application/pdf'}),/uploadedBy/);
assert.throws(()=>vault.metadata({sha256:'a'.repeat(64),originalType:'image/png',uploadedBy:'u1'}),/originalType/);
const m=vault.metadata({sha256:'a'.repeat(64),originalType:'application/pdf',uploadedBy:'u1'});
assert.equal(m.redacted,'true');
assert.equal(m.encrypted,'true');
assert.ok(!('originalName' in m),'File names must not be stored in plaintext metadata.');
assert.equal(vault.STORED_TYPE,'application/octet-stream');
assert.equal(vault.objectPathFor('documents',{caseId:'c1',fileId:'f1'}),'documents/c1/f1');
assert.equal(vault.objectPathFor('evidence',{caseId:'c1',fileId:'f1'}),'evidence/c1/f1');
assert.throws(()=>vault.objectPathFor('other',{caseId:'c1',fileId:'f1'}));
assert.equal(vault.custodyEntry({action:'upload',uid:'u1',caseId:'c',fileId:'f',sha256:'a'.repeat(64)}).action,'upload');
console.log('Evidence vault tests passed.');
